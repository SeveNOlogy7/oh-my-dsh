function success(text) {
  return { kind: 'success', text }
}

function failure(text) {
  return { kind: 'error', text }
}

function followup(agent, text) {
  if (!agent?.followup) throw new Error('agent followup is unavailable in this composition')
  agent.followup({ content: [{ type: 'text', text }], source: { kind: 'user' } })
}

/**
 * Settle a command that only reports something.
 *
 * A command result stays in the UI command plane and never becomes a
 * conversation message, so the model is not asked to react to it. The Client
 * half in `client.js` renders the returned text in the command row, which is
 * what makes it readable without waking the agent.
 */
function report(text) {
  return success(text)
}

function inputText(rawInput) {
  return String(rawInput ?? '').trim()
}

async function ensureOmd(workspace) {
  const dirs = ['rules', 'plans', 'drafts', 'notepads', 'tasks', 'background', 'runtime', 'logs', 'handoff', 'evidence', 'boulder']
  for (const dir of dirs) await ensureDir(omdPath(workspace, dir))
}

const CONFIG_TEMPLATE = `{
  // Oh-My-DSH project configuration. Comments and trailing commas are allowed.
  "keywordHook": true,
  "delegation": {
    "maxConcurrent": 5,
    "maxDepth": 1,
    "defaultBackground": false,
    "waitTimeoutMs": 600000
  },
  "taskSystem": { "enabled": false },
  "agents": {},
  "categories": {},
  "diagnostics": { "commands": [] }
}
`

const GITIGNORE = `# Generated by Oh-My-DSH: ephemeral orchestration state
logs/
runtime/
background/
boulder/
`

const README = `# .omd

Durable Oh-My-DSH state.

- \`config.jsonc\` — project configuration (JSONC).
- \`rules/\` — project rules injected into OMD agents.
- \`plans/\`, \`drafts/\` — planning artifacts.
- \`boulder/\`, \`boulder.json\` — per-session execution slots and a derived view.
- \`notepads/\` — append-only learnings, decisions, issues, verification.
- \`tasks/\` — optional durable task system.
- \`background/\`, \`runtime/\` — delegation records and results.
- \`ledger.jsonl\` — orchestration events.
- \`handoff/\` — session handoff documents.

Keep \`config.jsonc\`, \`rules/\`, \`plans/\`, \`notepads/\`, and \`tasks/\` in version
control if the project wants shared context. Runtime, logs, background, and
boulder slots are local.
`

export function createCommands(runtime) {
  const ctx = runtime.ctx
  const commands = []
  const add = (command) => commands.push(command)
  const t = (key, fallback) => localizedText(runtime.language, key, fallback)
  // The settings page is a browser surface with no filesystem access. It calls
  // this command through `ctx.remote.commands.execute(...)`, so the two forms
  // below are one operation with two callers: a human typing `/omd-config` and
  // the page reading or writing the same workspace file.
  const configPage = createConfigPage()

  add({
    name: 'omd-init',
    description: t('command.omd-init.description', 'Create the .omd layout and a commented configuration template.'),
    handler: async ({ agent }) => {
      const state = await runtime.stateFor(agent)
      await ensureOmd(state.cwd)
      const config = omdPath(state.cwd, 'config.jsonc')
      if (!(await exists(config))) await writeTextAtomic(config, CONFIG_TEMPLATE)
      const ignore = omdPath(state.cwd, '.gitignore')
      if (!(await exists(ignore))) await writeTextAtomic(ignore, GITIGNORE)
      const readme = omdPath(state.cwd, 'README.md')
      if (!(await exists(readme))) await writeTextAtomic(readme, README)
      const rulesReadme = omdPath(state.cwd, 'rules', 'README.md')
      if (!(await exists(rulesReadme))) {
        await writeTextAtomic(
          rulesReadme,
          '# Rules\n\nMarkdown rules in this directory are injected into OMD agents.\n\nFrontmatter supports `alwaysApply: true` and `globs: ["*.ts"]`.\n',
        )
      }
      await appendLedger(state.cwd, { event: 'init', agent: agent.id })
      return report(`.omd initialized at ${omdPath(state.cwd)}\nconfig: ${config}\nnext: /omd-ulw <goal> or /omd-plan <goal>`)
    },
  })

  add({
    name: 'omd-ulw',
    description: t('command.omd-ulw.description', 'Enter ultrawork mode and pursue the goal until verified.'),
    input: { hint: '<goal>' },
    handler: async ({ agent, rawInput }) => {
      const goal = inputText(rawInput)
      if (!goal) return failure('usage: /omd-ulw <goal>')
      const state = await runtime.stateFor(agent)
      await ensureOmd(state.cwd)
      await runtime.setMode(agent, 'ultrawork', { runId: `ulw-${Date.now().toString(36)}` })
      await appendLedger(state.cwd, { event: 'mode-set', mode: 'ultrawork', agent: agent.id })
      followup(agent, `[ultrawork] ${goal}`)
      return success('ultrawork mode active. The operating protocol is in the system prompt; work until the goal is verified.')
    },
  })

  add({
    name: 'omd-plan',
    description: t('command.omd-plan.description', 'Enter interview planning mode and produce an approved plan.'),
    input: { hint: '<goal>' },
    handler: async ({ agent, rawInput }) => {
      const goal = inputText(rawInput)
      const state = await runtime.stateFor(agent)
      await ensureOmd(state.cwd)
      await runtime.setMode(agent, 'plan')
      await appendLedger(state.cwd, { event: 'mode-set', mode: 'plan', agent: agent.id })
      followup(agent, `[plan] ${goal || 'Plan the work I just described.'}`)
      return success('planning mode active. Interview only owner decisions, then write .omd/plans/<slug>.md after approval.')
    },
  })

  add({
    name: 'omd-hyperplan',
    description: t('command.omd-hyperplan.description', 'Run five adversarial planning lanes and produce a stronger plan.'),
    input: { hint: '<goal>' },
    handler: async ({ agent, rawInput }) => {
      const goal = inputText(rawInput)
      const state = await runtime.stateFor(agent)
      await ensureOmd(state.cwd)
      await runtime.setMode(agent, 'hyperplan')
      await appendLedger(state.cwd, { event: 'mode-set', mode: 'hyperplan', agent: agent.id })
      followup(agent, `[hyperplan] ${goal || 'Harden the current plan.'}`)
      return success('hyperplan mode active. Five review lanes run before any implementation.')    },
  })

  add({
    name: 'omd-team',
    description: t('command.omd-team.description', 'Run a lead + parallel worker wave protocol.'),
    input: { hint: '<goal>' },
    handler: async ({ agent, rawInput }) => {
      const goal = inputText(rawInput)
      const state = await runtime.stateFor(agent)
      await ensureOmd(state.cwd)
      await runtime.setMode(agent, 'team')
      await appendLedger(state.cwd, { event: 'mode-set', mode: 'team', agent: agent.id })
      followup(agent, `[team] ${goal || 'Run the current work as a parallel team.'}`)
      return success('team mode active. The lead delegates independent tasks and verifies result files.')
    },
  })

  add({
    name: 'omd-start-work',
    description: t(
      'command.omd-start-work.description',
      'Start or resume execution of an approved plan with the Atlas protocol.',
    ),
    input: { hint: '[plan]' },
    handler: async ({ agent, rawInput }) => {
      const state = await runtime.stateFor(agent)
      await ensureOmd(state.cwd)
      const requested = inputText(rawInput)
      let plan = null
      if (requested) plan = await readPlan(state.cwd, requested)
      if (!plan) {
        const slot = await readBoulderSlot(state.cwd, state.stem)
        if (slot.ok && slot.value.active_plan) {
          plan = await readPlan(state.cwd, slot.value.active_plan)
        }
      }
      if (!plan) plan = await latestPlan(state.cwd, { status: 'approved' })
      if (!plan) plan = await latestPlan(state.cwd)
      if (!plan) {
        return failure('no plan found in .omd/plans. Run /omd-plan first, then /omd-start-work.')
      }
      await createBoulder({
        workspace: state.cwd,
        stem: state.stem,
        sessionId: agent.id,
        planPath: plan.source,
        planName: plan.title,
      })
      const protocol = await loadProtocol('start-work')
      const next = plan.open[0]
      await appendLedger(state.cwd, {
        event: 'start-work',
        plan: plan.source,
        task: next?.id ?? null,
        agent: agent.id,
      })
      followup(
        agent,
        `${protocol}\n\n---\nActive plan: ${plan.source}\nTitle: ${plan.title}\nProgress: ${plan.checked}/${plan.total}\nNext task: ${next ? `${next.id}. ${next.title}` : 'none (final verification)'}\n`,
      )
      return success(
        `execution started: ${plan.title} (${plan.checked}/${plan.total})\nplan: ${plan.source}\nnext: ${next ? `${next.id}. ${next.title}` : 'final verification'}`,
      )
    },
  })

  add({
    name: 'omd-stop-continuation',
    description: t(
      'command.omd-stop-continuation.description',
      'Stop OMD continuations, pause the boulder, and pause an active goal.',
    ),
    handler: async ({ agent }) => {
      const state = await runtime.stateFor(agent)
      await runtime.clearMode(agent)
      await clearBoulder(state.cwd, state.stem, 'paused')
      let goalText = 'no active goal'
      try {
        if (ctx.get('goals')?.get) {
          const goal = ctx.get('goals').get(agent)
          if (goal && goal.phase === 'active') {
            ctx.get('goals').pause(agent, { id: goal.id, revision: goal.revision })
            goalText = 'goal paused'
          }
        }
      } catch {
        // goal service optional
      }
      await appendLedger(state.cwd, { event: 'stop-continuation', agent: agent.id })
      return report(`continuations stopped; boulder paused; ${goalText}`)
    },
  })

  add({
    name: 'omd-handoff',
    description: t('command.omd-handoff.description', 'Write a continuation handoff document for a new session.'),
    handler: async ({ agent }) => {
      const state = await runtime.stateFor(agent)
      await ensureOmd(state.cwd)
      const slot = await readBoulderSlot(state.cwd, state.stem)
      const plans = await listPlans(state.cwd)
      const tasks = await new TaskStore(state.cwd).summary()
      let transcript = ''
      try {
        if (ctx.get('sessionQuery')?.readSession) {
          const snapshot = await ctx.get('sessionQuery').readSession(agent.id)
          const lines = []
          for (const event of snapshot.events) {
            const data = event.data ?? {}
            if (event.type === 'user/message' || event.type === 'assistant/message') {
              const text = (data.message?.content ?? [])
                .filter((block) => block?.type === 'text')
                .map((block) => block.text)
                .join('\n')
              if (text) lines.push(`${event.type === 'user/message' ? 'user' : 'assistant'}: ${text}`)
            }
          }
          transcript = lines.slice(-30).join('\n\n')
        }
      } catch {
        transcript = '(session transcript unavailable)'
      }
      let git = ''
      try {
        if (ctx.get('subprocess')?.resolveExecutable) {
          const executable = await ctx.get('subprocess').resolveExecutable('git')
          const handle = ctx.get('subprocess').spawn({
            argv: [executable, 'status', '--short', '--branch'],
            cwd: state.cwd,
            stdio: { stdin: 'ignore', stdout: { maxBytes: 20000 }, stderr: { maxBytes: 20000 } },
            graceMs: 3000,
          })
          await handle.done
          git = handle.collected.stdout?.readFrom(0)?.text ?? ''
        }
      } catch {
        git = '(git status unavailable)'
      }
      const stamp = new Date().toISOString().replace(/[:.]/g, '-')
      const file = omdPath(state.cwd, 'handoff', `${stamp}.md`)
      const body = [
        `# Handoff ${stamp}`,
        '',
        `session: ${agent.id}`,
        `cwd: ${state.cwd}`,
        `mode: ${state.mode?.mode ?? 'none'}`,
        `boulder: ${slot.ok ? `${slot.value.status} ${slot.value.plan_name ?? ''}` : 'none'}`,
        `plans: ${plans.map((plan) => `${plan.title} (${plan.checked}/${plan.total}, ${plan.status})`).join('; ') || 'none'}`,
        `tasks: ${tasks.total} total, ${tasks.in_progress} in progress, ${tasks.completed} done`,
        '',
        '## Git',
        '```',
        git.trim(),
        '```',
        '',
        '## Recent transcript',
        transcript,
        '',
        '## Next action',
        'Review the active plan, run /omd-start-work to resume, and continue from the first unchecked task.',
        '',
      ].join('\n')
      await writeTextAtomic(file, body)
      await appendLedger(state.cwd, { event: 'handoff', file, agent: agent.id })
      return report(`handoff written: ${file}`)
    },
  })

  add({
    name: 'omd-init-deep',
    description: t('command.omd-init-deep.description', 'Generate a hierarchical AGENTS.md context tree.'),
    handler: async ({ agent }) => {
      const state = await runtime.stateFor(agent)
      const protocol = await loadProtocol('init-deep')
      followup(agent, `${protocol}\n\nTarget workspace: ${state.cwd}`)
      return success('init-deep protocol sent. Write only AGENTS.md files that carry durable, local context.')
    },
  })

  add({
    name: 'omd-refactor',
    description: t('command.omd-refactor.description', 'Refactor a target with behavior-preserving verification.'),
    input: { hint: '<target>' },
    handler: async ({ agent, rawInput }) => {
      const target = inputText(rawInput)
      if (!target) return failure('usage: /omd-refactor <target>')
      const protocol = await loadProtocol('refactor')
      followup(agent, `${protocol}\n\nTarget: ${target}`)
      return success('refactor protocol sent.')
    },
  })

  add({
    name: 'omd-remove-ai-slops',
    description: t('command.omd-remove-ai-slops.description', 'Remove low-value generated comments and dead noise.'),
    handler: async ({ agent }) => {
      const protocol = await loadProtocol('remove-ai-slops')
      followup(agent, protocol)
      return success('AI-slop cleanup protocol sent.')
    },
  })

  add({
    name: 'omd-status',
    description: t('command.omd-status.description', 'Show the OMD status board.'),
    handler: async ({ agent }) => {
      const state = await runtime.stateFor(agent)
      const status = await buildStatus({
        workspace: state.cwd,
        agentId: agent.id,
        config: state.config,
        backgroundRegistry: runtime.registry,
      })
      return report(renderStatus(status))
    },
  })

  add({
    name: 'omd-config',
    description: t('command.omd-config.description', 'Show the resolved OMD configuration and its sources.'),
    // The hint advertises the write form. The bare command keeps its original
    // report; `set <json>` merges a partial patch into the session workspace's
    // `.omd/config.jsonc`, validates it against `schema/omd-config.schema.json`,
    // and answers with the new state. The settings page uses both forms.
    input: { hint: 'set <json>' },
    handler: async ({ agent, rawInput }) => {
      const state = await runtime.stateFor(agent)
      const parsed = parseConfigInput(rawInput)
      if (parsed.kind === 'usage') return failure(parsed.message)
      try {
        const result =
          parsed.kind === 'read'
            ? await configPage.read({ workspace: state.cwd, agentId: state.role, language: runtime.language })
            : await configPage.set({
                workspace: state.cwd,
                agentId: state.role,
                language: runtime.language,
                patch: parsed.patch,
              })
        // A rejected write is an error result, so the page and the chat cell
        // both show the validator's own message instead of a generic failure.
        if (result.ok === false) return failure(result.error.message)
        return report(JSON.stringify(result, null, 2))
      } catch (error) {
        return failure(`omd-config failed: ${String(error?.message ?? error)}`)
      }
    },
  })

  // A globally mounted row serves every preset, so it registers the whole
  // command surface and lets the per-agent policy decide what is usable. The
  // legacy per-preset row keeps its narrower, role-filtered set.
  if (runtime.global) return commands
  if (!['sisyphus', 'hephaestus', 'prometheus', 'atlas'].includes(runtime.agentId)) {
    return commands.filter((command) =>
      ['omd-init', 'omd-status', 'omd-config', 'omd-handoff', 'omd-stop-continuation'].includes(command.name),
    )
  }
  return commands
}

