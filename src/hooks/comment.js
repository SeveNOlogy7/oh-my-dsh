const PATTERNS = [
  { id: 'comment-restates-code', regex: /^\s*\/\/\s*(increment|decrement|return|set|initialize|call|create|declare|define|loop|check)\b/i, detail: 'comment restates the next operation' },
  { id: 'comment-narrates-process', regex: /^\s*\/\/\s*(now|then|next|first|second),?\s+(we|i|you|let'?s)\b/i, detail: 'comment narrates the agent process' },
  { id: 'ai-generated-banner', regex: /\b(AI[- ]generated|generated by (an )?(AI|LLM|assistant)|written by (an )?(AI|LLM))\b/i, detail: 'AI-generated banner' },
  { id: 'empty-todo', regex: /^\s*\/\/\s*(TODO|FIXME)\s*$/i, detail: 'empty TODO with no owner or intent' },
  { id: 'section-marker-noise', regex: /^\s*\/\/\s*[-=]{3,}\s*$/i, detail: 'decorative comment marker' },
  { id: 'chatty-obvious', regex: /^\s*\/\/\s*(this (function|method|class|code) (is|does|will)|here we)\b/i, detail: 'chatty obvious comment' },
]

/** Find high-confidence AI-slop comments in a written text. */
export function findCommentSlop(text) {
  if (!text) return []
  if (String(text).includes('omd-comment-checker-disable-file')) return []
  const hits = []
  const lines = String(text).split('\n')
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index]
    if (line.includes('@allow')) continue
    for (const pattern of PATTERNS) {
      if (pattern.regex.test(line)) {
        hits.push({ line: index + 1, text: line.trim(), rule: pattern.id, detail: pattern.detail })
        break
      }
    }
  }
  return hits
}

export function extractWrittenText(toolName, args) {
  if (toolName === 'write') return String(args?.content ?? '')
  if (toolName === 'edit') return `${args?.old_string ?? ''}\n${args?.new_string ?? ''}`
  return ''
}

export function formatSlopWarning(hits, filePath) {
  const lines = [
    `[OMD comment checker] ${hits.length} low-value comment(s) in ${filePath ?? 'the written file'}:`,
  ]
  for (const hit of hits.slice(0, 8)) {
    lines.push(`  line ${hit.line}: ${hit.text} — ${hit.detail}`)
  }
  lines.push('Remove comments that restate the code. Keep comments that explain why, constraints, or non-obvious behavior.')
  lines.push('Bypass one line with `@allow`, or the whole file with `omd-comment-checker-disable-file`.')
  return lines.join('\n')
}
