#!/usr/bin/env node
import { promises as fs } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { AGENT_IDS, AGENTS, presetIdFor, canDelegate } from '../src/agents/registry.js'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '..')
const OUT = path.join(ROOT, 'presets')

const pkg = JSON.parse(await fs.readFile(path.join(ROOT, 'package.json'), 'utf8'))

/**
 * The module specifier a preset row uses to reach this package. It must equal
 * the published package name: the row resolves from the profile's
 * `node_modules`, so a published scoped name (`@scope/oh-my-dsh`) would leave a
 * hard-coded bare name unresolvable and every preset broken. Renaming the
 * package therefore means regenerating the presets.
 */
const PLUGIN_SPECIFIER = pkg.name

function q(value) {
  return JSON.stringify(String(value))
}

function baseRows(agent) {
  const rows = []
  rows.push({ id: 'agent-instructions', name: '@deepseek-ai/dsh-agent-instructions', config: { maxBytes: 65536 } })
  rows.push({ id: 'time-context', name: '@deepseek-ai/dsh-time-context' })
  rows.push({ id: 'tool-pwsh', name: '@deepseek-ai/dsh-tool-pwsh', disabled: "process.platform !== 'win32'" })
  rows.push({ id: 'tool-bash', name: '@deepseek-ai/dsh-tool-bash', disabled: "process.platform === 'win32'" })
  rows.push({ id: 'tool-fs', name: '@deepseek-ai/dsh-tool-fs' })
  rows.push({
    id: 'tool-fs-search',
    name: '@deepseek-ai/dsh-tool-fs-search',
    config: { sampleOverCapGlobResults: false },
  })
  rows.push({ id: 'tool-jobs', name: '@deepseek-ai/dsh-tool-jobs' })
  rows.push({ id: 'skill-filesystem', name: '@deepseek-ai/dsh-skill-filesystem' })
  rows.push({ id: 'tool-skill', name: '@deepseek-ai/dsh-tool-skill' })
  rows.push({ id: 'command-goal', name: '@deepseek-ai/dsh-command-goal' })
  rows.push({ id: 'tool-goal', name: '@deepseek-ai/dsh-tool-goal' })
  rows.push({ id: 'tool-ask-user', name: '@deepseek-ai/dsh-tool-ask-user' })
  rows.push({ id: 'tool-todo', name: '@deepseek-ai/dsh-tool-todo', config: { allowParallelInProgress: true } })
  rows.push({ id: 'tool-web', name: '@deepseek-ai/dsh-tool-web', config: { fetch: true, searchTimeoutMs: 60000 } })
  rows.push({ id: 'present', name: '@deepseek-ai/dsh-tool-present' })
  if (canDelegate(agent.id)) {
    // Only the control row. An earlier revision also inserted
    // `@deepseek-ai/dsh-tool-subagent-control/list-agents`; the installed DSH no
    // longer ships that subpath as a Loader row, so the row never started and
    // every delegating preset was audited as broken — which hid all four primary
    // presets from the picker. The shipped composition loads the same package
    // once and leaves the follow-up tool to the package itself.
    rows.push({ id: 'tool-subagent-control', name: '@deepseek-ai/dsh-tool-subagent-control' })
  }
  rows.push({
    id: 'compaction',
    name: 'cordis:group',
    group: true,
    isolate: { compaction: true, toolResultPruner: true },
    config: [
      { id: 'compaction-basic', name: '@deepseek-ai/dsh-compaction-basic' },
      { id: 'command-compact', name: '@deepseek-ai/dsh-command-compact' },
      {
        id: 'tool-result-pruner',
        name: '@deepseek-ai/dsh-compaction-tool-result-pruner',
        config: { thresholdChars: 8192, headChars: 4096, tailChars: 1024 },
      },
    ],
  })
  // The OMD runtime row is deliberately NOT here. It is declared once at the
  // profile's top level by `presets/omd-runtime.patch.yml`, so its tools,
  // commands, skills and hooks exist in every preset; the preset id is what
  // tells the runtime which role it is serving. Nesting the row here instead is
  // what used to confine OMD to its own presets.
  return rows
}

function renderRow(row, indent) {
  const pad = ' '.repeat(indent)
  const lines = [`${pad}- id: ${row.id}`, `${pad}  name: ${q(row.name)}`]
  if (row.disabled) lines.push(`${pad}  disabled: !!js ${row.disabled}`)
  if (row.group) lines.push(`${pad}  group: true`)
  if (row.isolate) {
    lines.push(`${pad}  isolate:`)
    for (const [key, value] of Object.entries(row.isolate)) lines.push(`${pad}    ${key}: ${value}`)
  }
  if (row.config && Array.isArray(row.config)) {
    lines.push(`${pad}  config:`)
    for (const child of row.config) lines.push(...renderRow(child, indent + 4))
  } else if (row.config && Object.keys(row.config).length) {
    lines.push(`${pad}  config:`)
    for (const [key, value] of Object.entries(row.config)) {
      lines.push(`${pad}    ${key}: ${typeof value === 'string' ? q(value) : JSON.stringify(value)}`)
    }
  }
  return lines
}

function renderPreset(agent) {
  const presetId = presetIdFor(agent.id)
  const lines = [
    `# Generated by scripts/generate-presets.mjs. Do not edit by hand.`,
    `- insert:`,
    `    - id: preset-${presetId}`,
    `      name: '@deepseek-ai/dsh-agent-preset'`,
    `      config:`,
    `        id: ${presetId}`,
    `        name: ${q(agent.displayName)}`,
    `        description: ${q(agent.description)}`,
    `        order: ${agent.order}`,
    `        plugins:`,
  ]
  for (const row of baseRows(agent)) lines.push(...renderRow(row, 10))
  return `${lines.join('\n')}\n`
}

const UI_PATCH = `# Generated by scripts/generate-presets.mjs. Do not edit by hand.
# Browser asset row: it renders OMD command output in the Web UI.
#
# This row exists because the client-modules scan only composes browser bundles
# for Loader entries it resolves by package specifier. The runtime row names
# this package, which declares no \`dsh.client\`, so the scan finds no browser
# half there; the asset lives in its own package, "omd-ui", and this row is what
# the scan can see. Keeping the asset under its own name also avoids the
# "package resolves from multiple active Loader sources" rejection that two rows
# naming one package would trigger.
#
# "../ui/index.js" is resolved against this file's directory (the include plugin
# sets its base URL to the patch file's folder). It must name the entry file:
# Node's ESM resolver rejects a directory specifier with
# ERR_UNSUPPORTED_DIR_IMPORT, which left the row permanently inactive and the
# browser bundle unregistered.
- insert:
    - id: omd-ui
      name: "../ui/index.js"
`

const RUNTIME_PATCH = `# Generated by scripts/generate-presets.mjs. Do not edit by hand.
# The single OMD runtime row, mounted at the profile's top level.
#
# It carries no \`agent\` key on purpose. A row that named an agent would serve
# exactly one OMD role; this one is mounted once for the whole profile, so its
# tools, commands, skills and hooks exist in every preset, including the shipped
# \`standard\`, \`ptc\`, \`minimal\` and \`cordis\`. The role is resolved per session
# from the active preset id: \`omd-<role>\` is that role, anything else is the
# capability-only identity, which has orchestration but no persona.
#
# \`language\` is a per-row Config key. There is now exactly one such row, so it
# is a profile-wide setting rather than a per-preset one.
- insert:
    - id: omd-runtime
      name: ${q(PLUGIN_SPECIFIER)}
`

async function main() {
  const check = process.argv.includes('--check')
  await fs.mkdir(OUT, { recursive: true })
  const expected = new Map()
  for (const id of AGENT_IDS) {
    const agent = AGENTS[id]
    expected.set(path.join(OUT, `${presetIdFor(id)}.patch.yml`), renderPreset(agent))
  }
  expected.set(path.join(OUT, 'omd-ui.patch.yml'), UI_PATCH)
  expected.set(path.join(OUT, 'omd-runtime.patch.yml'), RUNTIME_PATCH)
  let failed = false
  for (const [file, content] of expected) {
    if (check) {
      let actual = ''
      try {
        actual = await fs.readFile(file, 'utf8')
      } catch {
        actual = ''
      }
      if (actual !== content) {
        console.error(`out of date: ${path.relative(ROOT, file)}`)
        failed = true
      }
    } else {
      await fs.writeFile(file, content, 'utf8')
    }
  }
  if (check && failed) process.exitCode = 1
  if (!check) console.log(`generated ${expected.size} preset patches in ${path.relative(ROOT, OUT)}`)
}

await main()
