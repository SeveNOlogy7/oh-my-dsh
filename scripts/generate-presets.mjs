#!/usr/bin/env node
import { promises as fs } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '..')
const OUT = path.join(ROOT, 'presets')

const pkg = JSON.parse(await fs.readFile(path.join(ROOT, 'package.json'), 'utf8'))

/**
 * The module specifier a preset row uses to reach this package. It must equal
 * the published package name: the row resolves from the profile's
 * `node_modules`, so a published scoped name (`@scope/oh-my-dsh`) would leave a
 * hard-coded bare name unresolvable and every preset broken. Renaming the
 * package therefore means regenerating the presets.
 */
const PLUGIN_SPECIFIER = pkg.name

function q(value) {
  return JSON.stringify(String(value))
}

// OMD no longer ships per-role agent presets. DSH's picker lists every
// registered preset and `PresetDefinition` has no hidden/selectable field, so
// eleven `omd-<role>` presets could not be hidden and only misled users, who
// cannot switch presets once a session's first turn starts. Roles are resolved
// through OMD's own channel instead, and the presets' plugin rows were a
// redundant copy of the shipped `standard` tool set anyway: OMD's tools are
// mounted by the profile-level `omd-runtime` row below, so nothing OMD provides
// is lost. The only rows this script still emits are the runtime row and the
// browser asset row.

const UI_PATCH = `# Generated by scripts/generate-presets.mjs. Do not edit by hand.
# Browser asset row: it renders OMD command output in the Web UI.
#
# This row exists because the client-modules scan only composes browser bundles
# for Loader entries it resolves by package specifier. The runtime row names
# this package, which declares no \`dsh.client\`, so the scan finds no browser
# half there; the asset lives in its own package, "omd-ui", and this row is what
# the scan can see. Keeping the asset under its own name also avoids the
# "package resolves from multiple active Loader sources" rejection that two rows
# naming one package would trigger.
#
# "../ui/index.js" is resolved against this file's directory (the include plugin
# sets its base URL to the patch file's folder). It must name the entry file:
# Node's ESM resolver rejects a directory specifier with
# ERR_UNSUPPORTED_DIR_IMPORT, which left the row permanently inactive and the
# browser bundle unregistered.
- insert:
    - id: omd-ui
      name: "../ui/index.js"
`

const RUNTIME_PATCH = `# Generated by scripts/generate-presets.mjs. Do not edit by hand.
# The single OMD runtime row, mounted at the profile's top level.
#
# It carries no \`agent\` key on purpose. A row that named an agent would serve
# exactly one OMD role; this one is mounted once for the whole profile, so its
# tools, commands, skills and hooks exist in every preset, including the shipped
# \`standard\`, \`ptc\`, \`minimal\` and \`cordis\`. The role is resolved per session
# from the session's own delegated \`subagent/descriptor\` label (\`omd:<role>\`),
# with the active preset kept only as the compatibility fallback for sessions
# allocated while OMD still published one preset per role. A session that
# resolves to neither is the capability-only identity, which has orchestration
# but no persona.
#
# \`language\` is a per-row Config key. There is now exactly one such row, so it
# is a profile-wide setting rather than a per-preset one.
- insert:
    - id: omd-runtime
      name: ${q(PLUGIN_SPECIFIER)}
`

async function main() {
  const check = process.argv.includes('--check')
  await fs.mkdir(OUT, { recursive: true })
  const expected = new Map()
  expected.set(path.join(OUT, 'omd-ui.patch.yml'), UI_PATCH)
  expected.set(path.join(OUT, 'omd-runtime.patch.yml'), RUNTIME_PATCH)
  let failed = false
  for (const [file, content] of expected) {
    if (check) {
      let actual = ''
      try {
        actual = await fs.readFile(file, 'utf8')
      } catch {
        actual = ''
      }
      if (actual !== content) {
        console.error(`out of date: ${path.relative(ROOT, file)}`)
        failed = true
      }
    } else {
      await fs.writeFile(file, content, 'utf8')
    }
  }
  if (check && failed) process.exitCode = 1

  // `--check` compares the files this script owns, so on its own it cannot see a
  // patch that should not be there at all. Regenerating therefore used to leave
  // a resurrected per-role preset in place, and `presets/` is exactly where one
  // would come back from. Scan for the strays the two generated files do not
  // account for.
  if (check) {
    const known = new Set([...expected.keys()].map((file) => path.basename(file)))
    const strays = (await fs.readdir(OUT))
      .filter((name) => name.endsWith('.patch.yml') && !known.has(name))
      .sort()
    if (strays.length) {
      for (const stray of strays) console.error(`stale patch: ${path.relative(ROOT, path.join(OUT, stray))}`)
      process.exitCode = 1
    }
  }

  if (!check) console.log(`generated ${expected.size} preset patches in ${path.relative(ROOT, OUT)}`)
}

await main()
